class _DotNamespace:
    """Lightweight namespace allowing R-style dot-syntax calls like `circos.track(...)`."""

    def __init__(self, mapping: dict[str, Any], name: str) -> None:
        self.__dict__.update(mapping)
        self._namespace_name = name

    def __repr__(self) -> str:
        keys = [k for k in self.__dict__ if not k.startswith("_")]
        return f"<circlize namespace {self._namespace_name!r} ({len(keys)} attributes)>"


